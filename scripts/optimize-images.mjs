// Generates responsive AVIF + WebP variants of the photos in public/gallery/ into public/img/
// and writes the typed manifest src/data/images.ts used by <AppPicture>. Besides the full-frame
// widths, every photo gets a 4:3 centre crop ("card", as the catalog cards frame it), so cards
// never download pixels that object-cover would cut away.
//
// sharp is intentionally not a project dependency (the Docker build never needs it). Run with:
//   npm i --no-save sharp@0.34 && node scripts/optimize-images.mjs
import { readdir, mkdir, writeFile } from 'node:fs/promises'
import { join, parse } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = fileURLToPath(new URL('..', import.meta.url))
const srcDir = join(root, 'public/gallery')
const outDir = join(root, 'public/img')
const WIDTHS = [480, 800, 1200, 1600]
const CARD_WIDTHS = [480, 800]
const encode = (img, base) =>
  Promise.all([
    img.clone().avif({ quality: 42, effort: 6 }).toFile(join(outDir, `${base}.avif`)),
    img.clone().webp({ quality: 70, effort: 6 }).toFile(join(outDir, `${base}.webp`)),
  ])

await mkdir(outDir, { recursive: true })
const manifest = {}

for (const file of (await readdir(srcDir)).sort()) {
  const { name, ext } = parse(file)
  if (!/\.(jpe?g|png)$/i.test(ext)) continue
  const input = join(srcDir, file)
  const { width, height } = await sharp(input).metadata()
  const widths = [...WIDTHS.filter((w) => w < width), width].filter((w, i, a) => a.indexOf(w) === i)
  for (const w of widths) await encode(sharp(input).resize({ width: w }), `${name}-${w}`)
  for (const w of CARD_WIDTHS)
    await encode(sharp(input).resize({ width: w, height: (w * 3) / 4, fit: 'cover' }), `${name}-card-${w}`)
  manifest[name] = { src: `/gallery/${file}`, width, height, widths, card: CARD_WIDTHS }
  console.log(name, widths.join(','))
}

const body = `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const

export type ImageName = keyof typeof images
`
await writeFile(join(root, 'src/data/images.ts'), body)
